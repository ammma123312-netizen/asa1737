"""Ask the ASA swarm through a GitHub issue and wait for its answer, asynchronously.

The swarm workflow (.github/workflows/asa-swarm.yml) runs when an issue gets the ``asa-ask``
label, uses the issue body as the prompt, and posts the answer as a comment ending in
``_Generated by the ASA Swarm workflow_``. This module is the client side of that contract, so
the Odysseus app (or a script) can submit a prompt, keep working, and collect the answer later.

Stdlib only. Needs a token that can write issues on the repository (fine-grained token with
"Issues: read and write", or ``GITHUB_TOKEN`` inside Actions). The token is sent only to the
GitHub API host.

CLI:
  python -m asa.swarm.issue_client ask "your question"          # prints the issue number
  python -m asa.swarm.issue_client ask --wait "your question"   # ...and waits for the answer
  python -m asa.swarm.issue_client get 42 [--wait]               # answer of issue 42
Environment: ASA_SWARM_REPO (owner/name), ASA_GITHUB_TOKEN or GITHUB_TOKEN, GITHUB_API_URL.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
import urllib.error
import urllib.request
from dataclasses import dataclass
from typing import Callable, Optional

LABEL = "asa-ask"
FOOTER = "_Generated by the ASA Swarm workflow_"
TITLE_MAX = 80


class SwarmError(RuntimeError):
    pass


class SwarmTimeout(SwarmError):
    pass


@dataclass
class Answer:
    issue: int
    text: str
    comment_url: str


def _default_transport(method: str, url: str, headers: dict, body: Optional[bytes]):
    req = urllib.request.Request(url, data=body, method=method, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return r.status, r.read()
    except urllib.error.HTTPError as e:
        return e.code, e.read()


def parse_answer(body: str) -> Optional[str]:
    """Extract the answer from a swarm comment, or None if the comment is not one."""
    if not body or FOOTER not in body:
        return None
    text = body[: body.rindex(FOOTER)].rstrip()
    if text.endswith("---"):
        text = text[:-3].rstrip()
    lines = text.split("\n")
    # First line is the "**DeepSeek-V4.1-Flash 763B** (ASA swarm, N free runners):" header.
    if lines and lines[0].startswith("**") and lines[0].rstrip().endswith(":"):
        lines = lines[1:]
    return "\n".join(lines).strip("\n")


def make_title(prompt: str) -> str:
    first = " ".join(prompt.split())
    if len(first) > TITLE_MAX:
        first = first[: TITLE_MAX - 1].rstrip() + "…"
    return f"[asa-ask] {first}"


class SwarmIssueClient:
    def __init__(self, repo: str, token: str, api: Optional[str] = None,
                 transport: Callable = _default_transport,
                 sleep: Callable[[float], None] = time.sleep,
                 clock: Callable[[], float] = time.monotonic):
        if not repo or repo.count("/") != 1:
            raise ValueError("repo must be 'owner/name'")
        if not token:
            raise ValueError("a GitHub token with issues:write is required")
        self.repo, self.token = repo, token
        self.api = (api or os.environ.get("GITHUB_API_URL") or "https://api.github.com").rstrip("/")
        self._transport, self._sleep, self._clock = transport, sleep, clock

    def _call(self, method: str, path: str, payload=None):
        headers = {
            "Authorization": f"Bearer {self.token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "asa-swarm-issue-client",
        }
        body = None
        if payload is not None:
            body = json.dumps(payload).encode()
            headers["Content-Type"] = "application/json"
        status, raw = self._transport(method, f"{self.api}/repos/{self.repo}{path}", headers, body)
        data = json.loads(raw) if raw else None
        if status >= 400:
            msg = data.get("message") if isinstance(data, dict) else raw[:200]
            raise SwarmError(f"GitHub API {method} {path}: {status} {msg}")
        return data

    def ask(self, prompt: str) -> int:
        """Open an issue with the prompt and label it asa-ask. Returns the issue number."""
        if not prompt.strip():
            raise ValueError("empty prompt")
        issue = self._call("POST", "/issues", {"title": make_title(prompt), "body": prompt})
        number = int(issue["number"])
        # Label in a separate call: the workflow listens for the `labeled` event.
        self._call("POST", f"/issues/{number}/labels", {"labels": [LABEL]})
        return number

    def answer(self, issue: int) -> Optional[Answer]:
        """The swarm's answer on this issue, or None if it has not arrived yet."""
        page = 1
        found = None
        while True:
            comments = self._call("GET", f"/issues/{issue}/comments?per_page=100&page={page}")
            for c in comments or []:
                text = parse_answer(c.get("body") or "")
                user = (c.get("user") or {}).get("login", "")
                # Only trust the Actions bot, so a human pasting the footer is not taken as the answer.
                if text is not None and user == "github-actions[bot]":
                    found = Answer(issue, text, c.get("html_url", ""))
            if not comments or len(comments) < 100:
                return found  # latest swarm answer wins (e.g. after a re-run)
            page += 1

    def wait(self, issue: int, timeout: float = 7200, interval: float = 30) -> Answer:
        """Poll until the answer arrives. Swarm runs take many minutes; the default is 2 h."""
        deadline = self._clock() + timeout
        while True:
            got = self.answer(issue)
            if got is not None:
                return got
            if self._clock() >= deadline:
                raise SwarmTimeout(f"no swarm answer on issue #{issue} after {timeout:.0f}s "
                                   "(the workflow comments only when the run succeeds)")
            self._sleep(interval)

    def ask_and_wait(self, prompt: str, timeout: float = 7200, interval: float = 30) -> Answer:
        return self.wait(self.ask(prompt), timeout=timeout, interval=interval)


def from_env() -> SwarmIssueClient:
    return SwarmIssueClient(
        repo=os.environ.get("ASA_SWARM_REPO", ""),
        token=os.environ.get("ASA_GITHUB_TOKEN") or os.environ.get("GITHUB_TOKEN", ""),
    )


def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="asa.swarm.issue_client", description=__doc__.split("\n")[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("ask")
    a.add_argument("prompt")
    g = sub.add_parser("get")
    g.add_argument("issue", type=int)
    for s in (a, g):
        s.add_argument("--wait", action="store_true")
        s.add_argument("--timeout", type=float, default=7200)
        s.add_argument("--interval", type=float, default=30)
    args = p.parse_args(argv)
    try:
        client = from_env()
        issue = client.ask(args.prompt) if args.cmd == "ask" else args.issue
        if args.cmd == "ask":
            print(f"issue #{issue}", file=sys.stderr)
        if args.wait:
            print(client.wait(issue, args.timeout, args.interval).text)
        elif args.cmd == "get":
            got = client.answer(issue)
            if got is None:
                print(f"no answer yet on issue #{issue}", file=sys.stderr)
                return 3
            print(got.text)
        else:
            print(issue)
        return 0
    except SwarmTimeout as e:
        print(e, file=sys.stderr)
        return 2
    except (SwarmError, ValueError) as e:
        print(e, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
